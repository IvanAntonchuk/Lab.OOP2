#ifndef IIMPORTSTRATEGY_H
#define IIMPORTSTRATEGY_H

#include <QString>
#include <vector>
#include "linkmanager.h"

/**
 * @brief Базовий інтерфейс для всіх стратегій імпорту посилань.
 * * Цей абстрактний клас є основою патерну "Стратегія" (Strategy) для процесу зчитування даних.
 * Він визначає загальний контракт для різноманітних алгоритмів імпорту (наприклад, із CSV або JSON).
 * Використання інтерфейсу дозволяє легко додавати нові формати імпорту без зміни основного коду програми.
 */
class IImportStrategy {
public:
    /**
     * @brief Віртуальний деструктор за замовчуванням.
     * Забезпечує коректне очищення ресурсів при видаленні об'єктів похідних класів-стратегій
     * через вказівник на базовий інтерфейс.
     */
    virtual ~IImportStrategy() = default;

    /**
     * @brief Суто віртуальний метод для імпорту даних із файлу.
     * Усі похідні класи-стратегії повинні реалізувати цей метод, надаючи конкретну логіку
     * парсингу (розбору) файлу відповідного формату.
     * * @param filePath Шлях до файлу, з якого потрібно імпортувати дані.
     * @return Вектор об'єктів LinkData, які були успішно зчитані та розпізнані з файлу.
     */
    virtual std::vector<LinkData> importData(const QString& filePath) const = 0;
};

#endif // IIMPORTSTRATEGY_H
